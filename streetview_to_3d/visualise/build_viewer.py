"""Package the modular viewer as one directly-openable HTML file.

No JS toolchain is required. Local ES modules are embedded as data URLs in
an import map; Three.js remains pinned to its CDN version. Gradio uses the
same builder so its source cannot drift from the standalone export, which
`python -m scripts.write_viewer` writes (see scripts/write_viewer.py).
"""
import base64
import json
import re
from pathlib import Path

SOURCE = Path(__file__).with_name("viewer_src")
OUTPUT = Path(__file__).with_name("viewer.html")


def build_viewer(config: dict | None = None) -> str:
    """The viewer as one HTML document, opening with config (sceneUrl, splatUrl, editable)."""
    imports = {
        "three": "https://unpkg.com/three@0.178.0/build/three.module.js",
        "three/addons/": "https://unpkg.com/three@0.178.0/examples/jsm/",
        # Gaussian splats; imported only when one is opened (scene-store.parseSplat)
        "@sparkjsdev/spark": "https://sparkjs.dev/releases/spark/0.1.10/spark.module.js",
    }
    for source in sorted(SOURCE.rglob("*.js")):
        encoded = base64.b64encode(source.read_bytes()).decode("ascii")
        imports[f"@viewer/{source.relative_to(SOURCE).with_suffix('').as_posix()}"] = f"data:text/javascript;base64,{encoded}"
    template = (SOURCE / "template.html").read_text(encoding="utf-8")
    template = template.replace("<!-- SCENE_MANAGER -->", (SOURCE / "ui" / "scene-manager.html").read_text(encoding="utf-8"))
    config_json = json.dumps(config or {}).replace("<", "\\u003c")
    template, count = re.subn(
        r'(<script id="viewer-config" type="application/json">)\s*\{\}\s*(</script>)',
        lambda match: match[1] + config_json + match[2],
        template,
    )
    if count != 1:
        raise ValueError("Expected one viewer-config element in template.html")
    return "<!-- Generated by python -m scripts.write_viewer; edit viewer_src/ instead. -->\n" + template.replace(
        "/* VIEWER_STYLES */", (SOURCE / "styles.css").read_text(encoding="utf-8")
    ).replace("/* VIEWER_IMPORTS */", json.dumps({"imports": imports}))

